-- Statistiques du site : visites anonymes (sans cookie) et journal de l'estimateur.
-- Les enregistrements passent par le serveur du site (clé service) ; seuls les admins lisent.
-- Sans risque : peut être relancé plusieurs fois.

-- ---------- Visites ----------
CREATE TABLE IF NOT EXISTS public.site_visits (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  session_id text NOT NULL,
  path text NOT NULL,
  source text,
  referrer_host text,
  device text,
  city text,
  country text
);
CREATE INDEX IF NOT EXISTS site_visits_created ON public.site_visits (created_at DESC);
CREATE INDEX IF NOT EXISTS site_visits_session ON public.site_visits (session_id, created_at);
ALTER TABLE public.site_visits ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "site_visits_admin_read" ON public.site_visits;
CREATE POLICY "site_visits_admin_read" ON public.site_visits FOR SELECT TO authenticated
  USING (public.has_role(auth.uid(),'admin') OR public.has_role(auth.uid(),'super_admin'));
GRANT SELECT ON public.site_visits TO authenticated;

-- ---------- Estimations ----------
CREATE TABLE IF NOT EXISTS public.estimations_log (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  session_id text,
  depart_ville text,
  depart_dept text,
  arrivee_ville text,
  arrivee_dept text,
  km numeric,
  vehicule text,
  option_trajet text,
  prix numeric,
  demande_envoyee boolean NOT NULL DEFAULT false,
  demande_at timestamptz,
  devis_id uuid
);
CREATE INDEX IF NOT EXISTS estimations_log_created ON public.estimations_log (created_at DESC);
ALTER TABLE public.estimations_log ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "estimations_admin_read" ON public.estimations_log;
CREATE POLICY "estimations_admin_read" ON public.estimations_log FOR SELECT TO authenticated
  USING (public.has_role(auth.uid(),'admin') OR public.has_role(auth.uid(),'super_admin'));
GRANT SELECT ON public.estimations_log TO authenticated;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'estimations_log') THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.estimations_log;
  END IF;
END $$;

-- ---------- Chiffres pour l'admin ----------
CREATE OR REPLACE FUNCTION public.admin_site_stats(p_days integer)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  d integer := greatest(1, least(coalesce(p_days, 30), 365));
  t0 timestamptz := date_trunc('day', now() AT TIME ZONE 'Europe/Paris') AT TIME ZONE 'Europe/Paris' - make_interval(days => d - 1);
  tp timestamptz := t0 - make_interval(days => d);
  res jsonb;
BEGIN
  IF NOT (public.has_role(auth.uid(),'admin') OR public.has_role(auth.uid(),'super_admin')) THEN
    RAISE EXCEPTION 'forbidden';
  END IF;
  WITH v AS (SELECT * FROM public.site_visits WHERE created_at >= t0),
  first_hit AS (SELECT DISTINCT ON (session_id) session_id, source, device, city FROM v ORDER BY session_id, created_at)
  SELECT jsonb_build_object(
    'days', d,
    'live', (SELECT count(DISTINCT session_id) FROM public.site_visits WHERE created_at >= now() - interval '5 minutes'),
    'visitors', (SELECT count(DISTINCT session_id) FROM v),
    'visitors_prev', (SELECT count(DISTINCT session_id) FROM public.site_visits WHERE created_at >= tp AND created_at < t0),
    'pageviews', (SELECT count(*) FROM v),
    'per_day', (SELECT coalesce(jsonb_agg(jsonb_build_object('day', g.day, 'visitors', coalesce(c.n, 0)) ORDER BY g.day), '[]'::jsonb)
                FROM (SELECT (t0 AT TIME ZONE 'Europe/Paris')::date + i AS day FROM generate_series(0, d - 1) i) g
                LEFT JOIN (SELECT (created_at AT TIME ZONE 'Europe/Paris')::date AS day, count(DISTINCT session_id) n FROM v GROUP BY 1) c USING (day)),
    'pages', (SELECT coalesce(jsonb_agg(x ORDER BY (x->>'n')::int DESC), '[]'::jsonb) FROM (
                SELECT jsonb_build_object('label', path, 'n', count(*)) x FROM v GROUP BY path ORDER BY count(*) DESC LIMIT 8) s),
    'sources', (SELECT coalesce(jsonb_agg(x), '[]'::jsonb) FROM (
                SELECT jsonb_build_object('label', coalesce(source, 'Lien direct'), 'n', count(*)) x FROM first_hit GROUP BY 1 ORDER BY count(*) DESC LIMIT 8) s),
    'devices', (SELECT coalesce(jsonb_agg(x), '[]'::jsonb) FROM (
                SELECT jsonb_build_object('label', coalesce(device, 'Autre'), 'n', count(*)) x FROM first_hit GROUP BY 1 ORDER BY count(*) DESC) s),
    'cities', (SELECT coalesce(jsonb_agg(x), '[]'::jsonb) FROM (
                SELECT jsonb_build_object('label', city, 'n', count(*)) x FROM first_hit WHERE city IS NOT NULL AND city <> '' GROUP BY city ORDER BY count(*) DESC LIMIT 8) s),
    'funnel', jsonb_build_object(
      'visitors', (SELECT count(DISTINCT session_id) FROM v),
      'saw_price', (SELECT count(DISTINCT coalesce(session_id, id::text)) FROM public.estimations_log WHERE created_at >= t0),
      'requested', (SELECT count(*) FROM public.estimations_log WHERE created_at >= t0 AND demande_envoyee),
      'signed', (SELECT count(*) FROM public.devis WHERE statut = 'accepte' AND accepted_at >= t0)
    )
  ) INTO res;
  RETURN res;
END $$;
REVOKE ALL ON FUNCTION public.admin_site_stats(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_site_stats(integer) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_estimation_stats(p_days integer)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  d integer := greatest(1, least(coalesce(p_days, 30), 365));
  t0 timestamptz := now() - make_interval(days => d);
  res jsonb;
BEGIN
  IF NOT (public.has_role(auth.uid(),'admin') OR public.has_role(auth.uid(),'super_admin')) THEN
    RAISE EXCEPTION 'forbidden';
  END IF;
  WITH e AS (SELECT * FROM public.estimations_log WHERE created_at >= t0)
  SELECT jsonb_build_object(
    'days', d,
    'total', (SELECT count(*) FROM e),
    'total_prev', (SELECT count(*) FROM public.estimations_log WHERE created_at >= t0 - make_interval(days => d) AND created_at < t0),
    'requested', (SELECT count(*) FROM e WHERE demande_envoyee),
    'avg_price', (SELECT round(avg(prix)) FROM e WHERE prix > 0),
    'avg_km', (SELECT round(avg(km)) FROM e WHERE km > 0),
    'trips', (SELECT coalesce(jsonb_agg(x), '[]'::jsonb) FROM (
      SELECT jsonb_build_object('label', coalesce(depart_ville,'?') || ' → ' || coalesce(arrivee_ville,'?'), 'n', count(*), 'req', count(*) FILTER (WHERE demande_envoyee)) x
      FROM e GROUP BY depart_ville, arrivee_ville ORDER BY count(*) DESC LIMIT 8) s),
    'bands', (SELECT coalesce(jsonb_agg(x ORDER BY (x->>'o')::int), '[]'::jsonb) FROM (
      SELECT jsonb_build_object('o', b.o, 'label', b.label, 'n', count(e.id), 'req', count(e.id) FILTER (WHERE e.demande_envoyee)) x
      FROM (VALUES (1,'< 100 €',0,100),(2,'100-200',100,200),(3,'200-300',200,300),(4,'300-400',300,400),(5,'400-600',400,600),(6,'> 600 €',600,1000000)) b(o,label,lo,hi)
      LEFT JOIN e ON e.prix >= b.lo AND e.prix < b.hi
      GROUP BY b.o, b.label) s),
    'recent', (SELECT coalesce(jsonb_agg(x ORDER BY x->>'created_at' DESC), '[]'::jsonb) FROM (
      SELECT jsonb_build_object('id', id, 'created_at', created_at, 'depart_ville', depart_ville, 'depart_dept', depart_dept,
        'arrivee_ville', arrivee_ville, 'arrivee_dept', arrivee_dept, 'km', km, 'vehicule', vehicule, 'prix', prix, 'demande_envoyee', demande_envoyee) x
      FROM public.estimations_log ORDER BY created_at DESC LIMIT 15) s)
  ) INTO res;
  RETURN res;
END $$;
REVOKE ALL ON FUNCTION public.admin_estimation_stats(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_estimation_stats(integer) TO authenticated;

